export function getInitialLanguage() {
  const saved = window.localStorage.getItem('trading-dashboard-language');
  if (saved === 'th' || saved === 'en') return saved;
  return navigator.language?.toLowerCase().startsWith('th') ? 'th' : 'en';
}
